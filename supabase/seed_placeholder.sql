-- ---------------------------------------------------------------------------
-- entregas
-- unique (pedido_id, data_prevista)
-- status entregue exige entregue_em
-- status != entregue exige entregue_em e entregue_por nulos
-- entregue_por fica null (FK para auth.users)
-- ---------------------------------------------------------------------------

INSERT INTO public.entregas (
  pedido_id,
  data_prevista,
  quantidade,
  status,
  observacoes,
  entregue_em,
  entregue_por
)
SELECT
  s.pedido_id,
  s.data_prevista,
  s.quantidade,
  s.status,
  s.observacoes,
  CASE
    WHEN s.status = 'entregue'::public.entrega_status
      THEN (s.data_prevista::timestamp + interval '10 hours 15 minutes')
        AT TIME ZONE 'America/Sao_Paulo'
    ELSE NULL
  END,
  NULL
FROM (
  SELECT
    p.id AS pedido_id,
    (week.monday + off.week_offset + dia.day_offset)::date AS data_prevista,
    p.quantidade,
    CASE
      WHEN (week.monday + off.week_offset + dia.day_offset)::date < week.today
        THEN 'entregue'::public.entrega_status
      WHEN (week.monday + off.week_offset + dia.day_offset)::date > week.today
        THEN 'pendente'::public.entrega_status
      ELSE (
        ARRAY[
          'pendente',
          'separado',
          'em_rota',
          'entregue'
        ]::public.entrega_status[]
      )[((row_number() OVER (
        PARTITION BY off.week_offset
        ORDER BY p.id
      ) - 1) % 4) + 1]
    END AS status,
    p.observacoes
  FROM public.pedidos p
  CROSS JOIN (
    SELECT
      (timezone('America/Sao_Paulo', now()))::date AS today,
      date_trunc(
        'week',
        timezone('America/Sao_Paulo', now())
      )::date AS monday
  ) week
  CROSS JOIN (
    VALUES (-7), (0), (7)
  ) AS off (week_offset)
  CROSS JOIN LATERAL (
    SELECT CASE p.dia_semana
      WHEN 'segunda' THEN 0
      WHEN 'terca' THEN 1
      WHEN 'quarta' THEN 2
      WHEN 'quinta' THEN 3
      WHEN 'sexta' THEN 4
      WHEN 'sabado' THEN 5
    END AS day_offset
  ) dia
  WHERE p.status = 'ativo'::public.pedido_status
    AND p.id >= '00000000-0000-4000-8000-000000000401'
    AND p.id <= '00000000-0000-4000-8000-000000000419'
) s;

